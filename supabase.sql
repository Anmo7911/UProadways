-- ZAYA — Supabase production database + storage setup
-- Run this in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  token text not null unique,
  title text not null,
  category text not null,
  price numeric(12,2) not null check (price >= 0),
  mrp numeric(12,2) not null check (mrp >= 0),
  colors jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  constraint products_colors_is_array check (jsonb_typeof(colors) = 'array')
);

create index if not exists products_created_at_idx
  on public.products (created_at desc);

create index if not exists products_category_idx
  on public.products (category);

alter table public.products enable row level security;

drop policy if exists "products_public_select" on public.products;
create policy "products_public_select"
on public.products
for select
to anon, authenticated
using (true);

drop policy if exists "products_authenticated_insert" on public.products;
create policy "products_authenticated_insert"
on public.products
for insert
to authenticated
with check (true);

drop policy if exists "products_authenticated_update" on public.products;
create policy "products_authenticated_update"
on public.products
for update
to authenticated
using (true)
with check (true);

drop policy if exists "products_authenticated_delete" on public.products;
create policy "products_authenticated_delete"
on public.products
for delete
to authenticated
using (true);

grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;

-- ------------------------------------------------------------
-- Recommended production admin allowlist
-- ------------------------------------------------------------
-- This table prevents an arbitrary signed-up customer account from
-- becoming an administrator.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

drop policy if exists "admin_users_self_select" on public.admin_users;
create policy "admin_users_self_select"
on public.admin_users
for select
to authenticated
using (user_id = auth.uid());

grant select on public.admin_users to authenticated;

