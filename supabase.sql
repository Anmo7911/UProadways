-- ------------------------------------------------------------
-- Storage bucket
-- ------------------------------------------------------------
-- Create the bucket in Dashboard > Storage > New bucket:
-- Name: product-images
-- Public bucket: ON
--
-- Supabase Storage public URLs are generated by getPublicUrl().
-- The upload itself remains protected by object RLS.

insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

-- Authenticated admins may upload objects.
drop policy if exists "product_images_authenticated_insert" on storage.objects;
create policy "product_images_authenticated_insert"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'product-images'
  and exists (
    select 1
    from public.admin_users
    where user_id = auth.uid()
  )
);

-- Authenticated admins may update objects.
drop policy if exists "product_images_authenticated_update" on storage.objects;
create policy "product_images_authenticated_update"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'product-images'
  and exists (
    select 1
    from public.admin_users
    where user_id = auth.uid()
  )
)
with check (
  bucket_id = 'product-images'
  and exists (
    select 1
    from public.admin_users
    where user_id = auth.uid()
  )
);

-- Authenticated admins may delete objects.
drop policy if exists "product_images_authenticated_delete" on storage.objects;
create policy "product_images_authenticated_delete"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'product-images'
  and exists (
    select 1
    from public.admin_users
    where user_id = auth.uid()
  )
);

-- Public product image delivery is handled by the bucket being public.
